/** Best-effort UK spelling for provider definitions, never user-authored text. */
export function toUkDictionarySpelling(text: string): string {
  return text.replace(
    /(?:https?:\/\/|www\.)[^\s<>]+|[\p{L}\p{N}._%+-]+@[\p{L}\p{N}.-]+\.[\p{L}]+|[\p{L}\p{M}]+(?:['’][\p{L}\p{M}]+)*/gu,
    (token) => {
      const match = /^([\p{L}\p{M}]+)(['’]s)?$/iu.exec(token);
      if (!match) return token;
      const [, word, possessive = ''] = match;
      const lower = word.toLowerCase();
      const replacement = Object.hasOwn(ukSpellings, lower)
        ? ukSpellings[lower]
        : undefined;
      if (!replacement) return token;
      if (word === lower) return replacement + possessive;
      if (word === word.toUpperCase())
        return replacement.toUpperCase() + possessive;
      if (word === word[0].toUpperCase() + word.slice(1).toLowerCase())
        return replacement[0].toUpperCase() + replacement.slice(1) + possessive;
      // Leave unusual casing alone; it may be a brand or identifier.
      return token;
    },
  );
}
